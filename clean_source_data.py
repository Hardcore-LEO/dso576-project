"""Clean the four supplied sources; never read dashboard data or modify raw files.

Usage: python clean_source_data.py --input-dir PATH
Outputs: data/cleaned/, cleaning_answers.md (generated by write_cleaning_report.py).
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd
from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parent
FILES = ['aei_claude_ai_2026-06-26.csv', 'BOS_M2025_dl.xlsx',
         'MSA_M2025_dl.xlsx', 'Occupation Data.xlsx']
NUMERIC = ['tot_emp', 'emp_prse', 'jobs_1000', 'loc_quotient', 'pct_total', 'pct_rpt',
           'h_mean', 'a_mean', 'mean_prse', 'h_pct10', 'h_pct25', 'h_median',
           'h_pct75', 'h_pct90', 'a_pct10', 'a_pct25', 'a_median', 'a_pct75', 'a_pct90']
AI_KEY = ['date_start', 'date_end', 'geo_id', 'geo_level', 'category_name',
          'hierarchy_level', 'metric_id', 'node_external_id']
BLS_KEY = ['area', 'area_type', 'naics', 'i_group', 'own_code', 'occ_code', 'o_group']
BEHAVIOR = ['use_case_work_pct', 'collaboration_bucket_augmentation_pct',
            'collaboration_bucket_automation_pct', 'ai_autonomy_mean']


def require(condition, message):
    if not bool(condition):
        raise ValueError(message)


def normalize(frame):
    """Strip boundary whitespace only; preserve meaningful text and identifier zeros."""
    frame = frame.copy()
    for col in frame:
        frame[col] = frame[col].astype('string').str.strip().replace('', pd.NA)
    return frame


def unique(frame, key, name):
    """Remove only identical duplicates; refuse to guess among conflicting records."""
    result = frame.drop_duplicates().copy()
    require(not result.duplicated(key).any(), f'{name}: conflicting duplicate keys {key}')
    return result, len(frame) - len(result)


def parse_bls_number(series, field):
    """Preserve censoring/missing reasons. A '#' wage is a lower bound, not an exact wage."""
    raw = series.astype('string').str.strip().replace('', pd.NA)
    status = pd.Series('reported', index=series.index, dtype='string')
    status.loc[raw.isna()] = 'blank_not_available'
    codes = {'*': 'wage_not_available', '**': 'employment_not_available',
             '#': 'top_coded_lower_bound', '~': 'below_reporting_threshold'}
    for token, label in codes.items():
        status.loc[raw.eq(token).fillna(False)] = label
    values = pd.to_numeric(raw.where(status.eq('reported')), errors='coerce').astype('Float64')
    require(not (status.eq('reported') & values.isna()).any(), f'Unexpected numeric token in {field}')
    require(values.dropna().ge(0).all() and np.isfinite(values.dropna().astype(float)).all(),
            f'Invalid numeric range in {field}')
    if raw.eq('#').any():
        require(field.startswith(('h_', 'a_')), f'Unexpected wage censoring in {field}')
    bound = pd.Series(pd.NA, index=series.index, dtype='Float64')
    if field.startswith(('h_', 'a_')):
        bound.loc[raw.eq('#').fillna(False)] = 115.0 if field.startswith('h_') else 239200.0
    return values, status, bound


def sha256(path):
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def save(frame, out, name, csv=True):
    frame.to_parquet(out / f'{name}.parquet', index=False)
    if csv:
        frame.to_csv(out / f'{name}.csv', index=False)


def clean_bls(path, out, audit):
    workbook = load_workbook(path, read_only=True, data_only=True)
    fields = [[str(x) if x is not None else None for x in row]
              for row in workbook['Field Descriptions'].values]
    workbook.close()
    (out / (path.stem + '_field_descriptions.json')).write_text(
        json.dumps(fields, indent=2, ensure_ascii=False), encoding='utf-8')
    raw = pd.read_excel(path, sheet_name=path.stem, dtype='string', keep_default_na=False)
    raw.columns = raw.columns.str.lower()
    d = normalize(raw)
    require(not d[BLS_KEY + ['area_title', 'prim_state', 'occ_title']].isna().any().any(),
            'Missing BLS identifier or title')
    d, duplicates = unique(d, BLS_KEY, path.name)
    require(d['area'].str.fullmatch(r'\d+').all(), 'Invalid BLS area code')
    require(d['occ_code'].str.fullmatch(r'\d{2}-\d{4}').all(), 'Invalid BLS occupation code')
    require(d['naics'].eq('000000').all() and d['own_code'].eq('1235').all(),
            'Unexpected BLS industry/ownership scope; revise filtering explicitly')
    require(d['o_group'].isin(['detailed', 'major', 'total', 'broad', 'minor']).all(), 'Unknown BLS level')
    require(d['area_type'].eq('6' if path.name.startswith('BOS') else '4').all(), 'Wrong BLS area type')
    for field in NUMERIC:
        values, status, bound = parse_bls_number(d[field], field)
        d[field], d[field + '_status'] = values, status
        if field.startswith(('h_', 'a_')):
            d[field + '_lower_bound'] = bound
    for field in ['annual', 'hourly']:
        require(d[field].dropna().str.upper().isin(['TRUE', 'FALSE']).all(), f'Unknown {field} flag')
        d[field] = d[field].str.upper().map({'TRUE': True, 'FALSE': False}).astype('boolean')
    d['source_file'] = path.name
    d['oews_release'] = '2025-05'
    d = d.sort_values(BLS_KEY).reset_index(drop=True)
    audit[path.name] = {'input_rows': len(raw), 'clean_rows': len(d), 'exact_duplicates_removed': duplicates,
                       'occupation_levels': d['o_group'].value_counts().to_dict(),
                       'numeric_status_counts': {k: d[k + '_status'].value_counts().to_dict() for k in NUMERIC}}
    save(d, out, path.stem.lower() + '_clean', csv=False)
    print(f'Cleaned {path.name}: {len(d):,} rows', flush=True)
    return d


def clean_ai(path, out, audit):
    raw = pd.read_csv(path, dtype='string', keep_default_na=False)
    d = normalize(raw)
    require(not d.isna().any().any(), 'Unexpected missing AEI source field')
    d, duplicates = unique(d, AI_KEY, 'AEI')
    for field in ['date_start', 'date_end']:
        d[field] = pd.to_datetime(d[field], format='%Y-%m-%d', errors='raise')
    require(d.date_end.gt(d.date_start).all(), 'Invalid AEI interval')
    d['value'] = pd.to_numeric(d['value'], errors='raise').astype('float64')
    levels = pd.to_numeric(d['hierarchy_level'], errors='raise')
    require(levels.mod(1).eq(0).all(), 'Noninteger hierarchy level')
    d['hierarchy_level'] = levels.astype('int64')
    require(np.isfinite(d.value).all() and d.value.ge(0).all(), 'Invalid AEI numeric value')
    require(d.loc[d.metric_id.str.endswith('pct'), 'value'].between(0, 100).all(), 'AEI percentage outside 0..100')
    require(d.loc[d.metric_id.eq('ai_autonomy_mean'), 'value'].between(1, 5).all(), 'Invalid autonomy scale')
    require(d.geo_level.isin(['global', 'country', 'subregion']).all(), 'Unknown AEI geography')
    require(d.category_name.isin(['overall', 'onet', 'request', 'soc_occupation']).all(), 'Unknown AEI category')
    require(d.hierarchy_level.between(0, 3).all(), 'Unknown hierarchy level')
    leaves = d.category_name.eq('soc_occupation') & d.hierarchy_level.eq(0)
    require(d.loc[leaves, 'node_external_id'].str.fullmatch(r'\d{2}-\d{4}\.\d{2}').all(), 'Invalid AEI O*NET code')
    d['source_file'] = path.name
    d['source_release'] = '2026-06-26'
    # Preserve the complete national/international source, including non-project categories.
    save(d, out, 'aei_claude_ai_clean', csv=False)
    audit[path.name] = {'input_rows': len(raw), 'clean_rows': len(d), 'exact_duplicates_removed': duplicates,
                       'period_rows': d.date_start.dt.strftime('%Y-%m-%d').value_counts().to_dict(),
                       'category_rows': d.category_name.value_counts().to_dict()}
    coverage = d.groupby(['date_start', 'date_end', 'geo_level', 'category_name',
                         'hierarchy_level', 'metric_id'], dropna=False).size().reset_index(name='published_rows')
    coverage.to_csv(out / 'aei_metric_coverage.csv', index=False)
    print(f'Cleaned {path.name}: {len(d):,} rows', flush=True)
    return d


def build_occupation_context(ai, onet, out):
    select = ai[ai.category_name.eq('soc_occupation') & ai.hierarchy_level.eq(0)
                & ai.geo_id.isin(['GLOBAL', 'USA', 'US-CA'])].copy()
    key = ['date_start', 'date_end', 'geo_id', 'geo_level', 'node_external_id']
    require(select.groupby(key, dropna=False).node_name.nunique().le(1).all(), 'Conflicting AI occupation titles')
    names = select[key + ['node_name']].drop_duplicates()
    wide = select.pivot(index=key, columns='metric_id', values='value').reset_index()
    wide.columns.name = None
    wide = wide.merge(names, on=key, validate='one_to_one')
    wide = wide.rename(columns={'node_external_id': 'onet_soc_code', 'node_name': 'aei_occupation_title'})
    wide['soc_code'] = wide.onet_soc_code.str[:7]
    wide = wide.merge(onet[['onet_soc_code', 'onet_title']], on='onet_soc_code', how='left',
                      validate='many_to_one', indicator='onet_title_match')
    wide['onet_title_match'] = wide.onet_title_match.astype('string')
    save(wide, out, 'occupation_ai_by_scope')
    latest = ai.date_start.max()
    global_may = wide[wide.geo_id.eq('GLOBAL') & wide.date_start.eq(latest)].copy()
    # Ranges describe published extensions; they are neither confidence intervals nor averages.
    summaries = []
    for soc, g in global_may.groupby('soc_code', sort=True):
        row = {'soc_code': soc, 'ai_context_geo': 'GLOBAL', 'ai_period_start': latest,
               'ai_period_end': g.date_end.iloc[0], 'published_ai_extensions': len(g),
               'published_onet_codes': ';'.join(sorted(g.onet_soc_code.tolist()))}
        for metric in BEHAVIOR:
            observed = g[metric].dropna()
            row[metric + '_min'] = observed.min() if len(observed) else np.nan
            row[metric + '_max'] = observed.max() if len(observed) else np.nan
            row[metric + '_n_extensions'] = len(observed)
        summaries.append(row)
    summary = pd.DataFrame(summaries)
    known = onet.groupby('soc_code').size().rename('dictionary_extensions').reset_index()
    summary = summary.merge(known, on='soc_code', how='left', validate='one_to_one')
    save(summary, out, 'global_occupation_context')
    # Both months and all three geographies remain distinct, without retrospective fills.
    trend = wide[['date_start', 'date_end', 'geo_id', 'onet_soc_code', 'aei_occupation_title', 'pct']].copy()
    starts = sorted(trend.date_start.unique())
    require([pd.Timestamp(x).strftime('%Y-%m-%d') for x in starts] == ['2026-04-01', '2026-05-01'],
            'This release comparison requires April and May 2026')
    periods = []
    for label, start in zip(['april', 'may'], starts):
        part = trend[trend.date_start.eq(start)].drop(columns=['date_start', 'date_end', 'aei_occupation_title'])
        periods.append(part.rename(columns={'pct': label + '_usage_share_pct'}))
    change = periods[0].merge(periods[1], on=['geo_id', 'onet_soc_code'], how='outer', validate='one_to_one')
    change['change_percentage_points'] = change.may_usage_share_pct - change.april_usage_share_pct
    change['both_months_published'] = change[['april_usage_share_pct', 'may_usage_share_pct']].notna().all(axis=1)
    save(change, out, 'occupation_usage_month_comparison')
    return wide, summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input-dir', required=True, type=Path)
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'data' / 'cleaned')
    args = parser.parse_args()
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    sources = [args.input_dir.resolve() / name for name in FILES]
    for path in sources:
        require(path.is_file(), f'Source missing: {path}')
    manifest = [{'file': p.name, 'bytes': p.stat().st_size, 'sha256': sha256(p)} for p in sources]
    audit = {}
    bls = pd.concat([clean_bls(p, out, audit) for p in sources[1:3]], ignore_index=True)
    require(not bls.duplicated(BLS_KEY).any(), 'BOS/MSA overlap in full keys')
    raw_onet = pd.read_excel(sources[3], sheet_name='Occupation Data', dtype='string', keep_default_na=False)
    onet = normalize(raw_onet).rename(columns={'O*NET-SOC Code': 'onet_soc_code', 'Title': 'onet_title',
                                             'Description': 'description'})
    onet, duplicates = unique(onet, ['onet_soc_code'], 'O*NET')
    require(not onet.isna().any().any(), 'Missing O*NET field')
    require(onet.onet_soc_code.str.fullmatch(r'\d{2}-\d{4}\.\d{2}').all(), 'Invalid O*NET code')
    onet['soc_code'] = onet.onet_soc_code.str[:7]
    onet = onet.sort_values('onet_soc_code').reset_index(drop=True)
    save(onet, out, 'occupations')
    audit[FILES[3]] = {'input_rows': len(raw_onet), 'clean_rows': len(onet), 'exact_duplicates_removed': duplicates}
    ai = clean_ai(sources[0], out, audit)
    wide, summary = build_occupation_context(ai, onet, out)
    # Retain aggregate BLS rows only in the full cleaned source outputs.
    ca = bls[bls.prim_state.eq('CA') & bls.o_group.eq('detailed')].copy()
    require(not ca.duplicated(['area', 'occ_code']).any(), 'CA area/occupation grain is not unique')
    require(ca.area_title.str.endswith(', CA').where(ca.area_type.eq('4'), True).all(),
            'Potential cross-state California metro requires explicit geographic review')
    ca = ca.rename(columns={'area': 'area_code', 'area_title': 'area_name',
                            'occ_code': 'soc_code', 'occ_title': 'occupation_title'})
    ca = ca.merge(summary, on='soc_code', how='left', validate='many_to_one', indicator='ai_parent_match')
    ca['ai_parent_match'] = ca.ai_parent_match.astype('string')
    ca['has_global_work_use_context'] = ca.use_case_work_pct_n_extensions.fillna(0).gt(0)
    require(len(ca) == int((bls.prim_state.eq('CA') & bls.o_group.eq('detailed')).sum()), 'Join changed row count')
    ca = ca.sort_values(['area_code', 'soc_code']).reset_index(drop=True)
    save(ca, out, 'occupation_area')
    # A bridge is a separate lookup. Never sum employment after expanding its rows.
    bridge = ca[['soc_code', 'occupation_title']].drop_duplicates().merge(onet, on='soc_code', how='outer',
                                                                       validate='one_to_many', indicator='match_status')
    bridge['match_status'] = bridge.match_status.astype('string')
    save(bridge, out, 'occupation_code_bridge')
    matches = []
    universes = {'ca_oews': set(ca.soc_code), 'onet_dictionary': set(onet.soc_code),
                 'global_latest_ai': set(summary.soc_code)}
    for soc in sorted(set.union(*universes.values())):
        matches.append({'soc_code': soc, **{k: soc in v for k, v in universes.items()}})
    pd.DataFrame(matches).to_csv(out / 'soc_match_audit.csv', index=False)
    unknown = wide[wide.onet_title_match.eq('left_only')][['onet_soc_code', 'aei_occupation_title']].drop_duplicates()
    unknown.to_csv(out / 'aei_codes_not_in_dictionary.csv', index=False)
    area = ca.groupby(['area_code', 'area_name'], as_index=False).agg(
        occupation_cells=('soc_code', 'size'), published_employment_cells=('tot_emp', 'count'),
        exact_median_wage_cells=('a_median', 'count'),
        global_work_use_context_cells=('has_global_work_use_context', 'sum'))
    area['global_context_coverage_pct'] = area.global_work_use_context_cells / area.occupation_cells * 100
    sums = ca.groupby('area_code').tot_emp.sum(min_count=1)
    area['published_employment_cell_sum'] = area.area_code.map(sums)
    save(area, out, 'area_summary')
    # Descriptive ordering only: no missing exposure/growth or invented policy weights.
    review = ca[ca.has_global_work_use_context & ca.tot_emp.notna()].sort_values(
        ['tot_emp', 'area_code', 'soc_code'], ascending=[False, True, True]).head(20).copy()
    review['ordering_basis'] = 'published_employment_descending_not_ai_priority'
    save(review, out, 'largest_workforces_with_ai_context')
    missing = []
    for name, frame in [('occupation_area', ca), ('occupations', onet), ('occupation_ai_by_scope', wide)]:
        for field in frame:
            count = int(frame[field].isna().sum())
            missing.append({'dataset': name, 'field': field, 'rows': len(frame), 'missing_rows': count,
                            'missing_pct': count / len(frame) * 100})
    pd.DataFrame(missing).to_csv(out / 'missingness.csv', index=False)
    # Reconciliation ensures output completeness and joins do not silently multiply rows.
    audit['results'] = {'ca_rows': len(ca), 'ca_areas': ca.area_code.nunique(), 'ca_socs': ca.soc_code.nunique(),
                        'global_context_cells': int(ca.has_global_work_use_context.sum()),
                        'ca_socs_without_global_context': ca.loc[~ca.has_global_work_use_context, 'soc_code'].nunique(),
                        'dictionary_rows': len(onet), 'dictionary_parent_socs': onet.soc_code.nunique(),
                        'ai_full_codes_absent_from_dictionary': unknown.onet_soc_code.nunique(),
                        'ca_socs_without_dictionary_match': len(universes['ca_oews'] - universes['onet_dictionary']),
                        'latest_period': ai.date_start.max().strftime('%Y-%m-%d'),
                        'source_hashes_unchanged': all(sha256(p) == m['sha256'] for p, m in zip(sources, manifest))}
    require(audit['results']['source_hashes_unchanged'], 'Raw source changed during execution')
    (out / 'source_manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    (out / 'cleaning_audit.json').write_text(json.dumps(audit, indent=2, default=int), encoding='utf-8')
    from write_cleaning_report import write_report
    write_report(ROOT, out, audit, ca, wide, area, review)
    print(json.dumps(audit['results'], indent=2, default=int), flush=True)


if __name__ == '__main__':
    main()
